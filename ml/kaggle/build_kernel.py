"""Package ml/toxicity into a single Kaggle script kernel and push it to a T4 GPU.

    python kaggle/build_kernel.py            # writes kaggle/kernel/ and pushes
    kaggle kernels status harshithvarma007/toxic-comments-transformer
    kaggle kernels output harshithvarma007/toxic-comments-transformer -p artifacts/kaggle

Training args can be overridden with TRAIN_ARGS="--epochs 3 --batch-size 64".
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent / "toxicity"
OUT = HERE / "kernel"
SLUG = os.environ.get("KAGGLE_KERNEL", "harshithvarma007/toxic-comments-transformer")
TRAIN_ARGS = os.environ.get("TRAIN_ARGS", "--epochs 3 --batch-size 64 --lr 1e-4 --max-len 128 --eval-every 1000")

sources = {p.name: p.read_text() for p in sorted(PKG.glob("*.py"))}

runner = f'''# Auto-generated by ml/kaggle/build_kernel.py — edit ml/toxicity/*.py instead.
import os, subprocess, sys, shutil
from pathlib import Path

SOURCES = {json.dumps(sources)}

work = Path("/kaggle/working")
src = work / "src" / "toxicity"
src.mkdir(parents=True, exist_ok=True)
for name, code in SOURCES.items():
    (src / name).write_text(code)

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "onnx", "onnxruntime", "onnxscript"], check=True)
env = dict(os.environ, TOXIC_ML_HOME=str(work), TOXIC_RAW_DIR="/kaggle/input", PYTHONPATH=str(work / "src"))
run = lambda *a: subprocess.run([sys.executable, "-m", *a], check=True, env=env, cwd=work)
subprocess.run(["nvidia-smi"])
run("toxicity.data")
run("toxicity.train", *{TRAIN_ARGS.split()!r})
run("toxicity.export")
shutil.rmtree(work / "data", ignore_errors=True)
shutil.rmtree(work / "src", ignore_errors=True)
print("ARTIFACTS:", [str(p) for p in (work / "artifacts").rglob("*")])
'''

OUT.mkdir(exist_ok=True)
(OUT / "train_kernel.py").write_text(runner)
(OUT / "kernel-metadata.json").write_text(json.dumps({
    "id": SLUG,
    "title": "Toxic Comments Transformer",
    "code_file": "train_kernel.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
    "machine_shape": "NvidiaTeslaT4",
    "competition_sources": ["jigsaw-toxic-comment-classification-challenge"],
    "dataset_sources": ["reihanenamdari/youtube-toxicity-data"],
    "kernel_sources": [],
}, indent=2))
print(f"wrote {OUT}")
if "--no-push" not in sys.argv:
    kaggle = Path(sys.executable).parent / "kaggle"
    subprocess.run([str(kaggle), "kernels", "push", "-p", str(OUT), "--accelerator", "NvidiaTeslaT4"], check=True)
